class AutresHooks(NamedTuple):
    """Les hooks d'un autre outil, que brancher Lintorn rendrait muets."""
    dossier: Path
    noms: list[str] | None   # None : dossier illisible, on ne sait pas ce qui y tourne
    reglage: str = ""        # `core.hooksPath` qui les désigne ("" : le dossier par défaut)


class Passage(NamedTuple):
    """Ce que git et Lintorn ont VU, plutôt que ce que dit le texte d'un hook."""
    vu: datetime | None       # dernière fois qu'un hook a lancé Lintorn
    pousse: datetime | None   # dernier push que git a noté
    couvert: bool             # le hook appelle Lintorn : il a vérifié ce push, ou tourné depuis
    malgre_refus: bool = False  # ce push portait un commit que Lintorn avait refusé, sans recours


class Conseil(NamedTuple):
    """Où, et quoi, ajouter pour que le pre-push d'un autre outil lance Lintorn."""
    fichier: Path      # le fichier à modifier
    consigne: str      # la phrase qui dit où : « ajoute cette ligne a … »
    ajout: str         # ce qu'on y ajoute
    langage: str       # du bloc de code du rapport : bash, yaml, json
    ensuite: str = ""  # la commande à lancer après, s'il y en a une
    garde: str = ""    # la mise en garde à lire avant de copier, s'il y en a une


# Les seuls noms que git lance (githooks(5)). Un README ou un script d'aide
# exécutable posé dans le dossier n'est pas un hook : le compter faisait
# refuser l'installation pour des hooks qui n'existent pas.
NOMS_DE_HOOKS = frozenset({
    "applypatch-msg", "pre-applypatch", "post-applypatch", "pre-commit",
    "pre-merge-commit", "prepare-commit-msg", "commit-msg", "post-commit",
    "pre-rebase", "post-checkout", "post-merge", "pre-push", "pre-receive",
    "update", "proc-receive", "post-receive", "post-update",
    "reference-transaction", "push-to-checkout", "pre-auto-gc", "post-rewrite",
    "sendemail-validate", "fsmonitor-watchman", "p4-changelist",
    "p4-prepare-changelist", "p4-post-changelist", "p4-pre-submit",
    "post-index-change",
})

# Dans `.lintorn/etat.json` : quand un hook a lancé Lintorn pour la dernière
# fois, et le dossier de hooks qu'un `lintorn hook --force` a remplacé.
CLE_PASSAGE = "dernier_passage_hook"
CLE_REMPLACES = "hooks_remplaces"

# Les commits vérifiés, et refusés, dont on garde la trace : de quoi couvrir
# les derniers push, sans grossir sans fin.
TRACE_MAX = 100

# git note chaque push dans le journal des branches distantes, sous ce
# libellé — jamais traduit. Un `fetch` y écrit autre chose.
LIBELLE_PUSH = "update by push"

_UN_COMMIT = re.compile(r"[0-9a-f]{40}(?:[0-9a-f]{24})?")

# Ces outils RÉÉCRIVENT leurs scripts du dossier de hooks (`pre-commit
# install`, `lefthook install`, le `npm install` suivant) : une ligne ajoutée
# à la main y disparaissait au passage d'après. Seule leur config dure.
# Chacun est reconnu à la marque qu'il écrit dans ses scripts — lue pour
# choisir le CONSEIL, jamais pour juger : le verdict vient du passage noté.
MARQUES = (
    ("pre-commit", "File generated by pre-commit"),
    ("lefthook", "call_lefthook"),
    ("simple-git-hooks", "SKIP_SIMPLE_GIT_HOOKS"),
)

# Ce que porte un hook Lintorn qui lance aussi ceux des autres sous-projets du
# dépôt. Une copie d'une version précédente ne le porte pas.
MARQUE_VOISINS = "LINTORN_VOISIN"


def script_du_hook() -> str:
    """Le hook de Lintorn tel qu'un autre hook l'appelle : depuis le sommet du dépôt.

    Le hook COMPLET, pas `lintorn rapide` : lui seul se place dans le bon
    sous-projet d'un monorepo (git lance les hooks depuis le sommet, et
    `lintorn rapide` y auditait la racine), laisse passer un push que des
    outils n'ont pas pu vérifier au lieu de le bloquer, et dit à Lintorn qu'un
    hook l'appelle — c'est ce passage noté qui prouve au contrôle que l'appel
    tourne vraiment.
    """
    return shlex.quote(f"{config.HOOKS_POUR_GIT}/pre-push".replace("\\", "/"))


def ligne_a_ajouter() -> str:
    return f'{script_du_hook()} "$@" || exit 1'


def _outil(autres: AutresHooks) -> str | None:
    for nom in autres.noms or ():
        try:
            texte = (autres.dossier / nom).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for outil, marque in MARQUES:
            if marque in texte:
                return outil
    return None


def conseil(autres: AutresHooks) -> Conseil:
    """Où, et quoi, ajouter pour que les hooks de `autres` lancent aussi Lintorn."""
    sommet = config.SOMMET_GIT or config.RACINE
    script = script_du_hook()
    # Un chemin à espace sort entre apostrophes : YAML les mangerait, et
    # l'outil couperait le chemin en deux. Une chaîne JSON est aussi du YAML.
    en_yaml = json.dumps(script, ensure_ascii=False) if script.startswith("'") else script
    outil = _outil(autres)
    if outil == "pre-commit":
        fichier = sommet / ".pre-commit-config.yaml"
        # `verbose` : sans lui, pre-commit n'affiche ce que dit Lintorn que s'il
        # refuse. « Push autorise SANS verification complete » devenait « Passed ».
        return Conseil(
            fichier, f"pre-commit reecrit ses scripts : ajoute ce bloc a "
                     f"{chemins.relatif(fichier)}, dans la liste `repos:`",
            "  - repo: local\n    hooks:\n      - id: lintorn\n        name: lintorn\n"
            f"        entry: {en_yaml}\n        language: system\n"
            "        stages: [pre-push]\n        pass_filenames: false\n        always_run: true\n"
            "        verbose: true",
            "yaml", "pre-commit install --hook-type pre-push")
    if outil == "lefthook":
        fichier = next((sommet / nom for nom in ("lefthook.yml", ".lefthook.yml", "lefthook.yaml",
                                                  ".lefthook.yaml") if (sommet / nom).is_file()),
                       sommet / "lefthook.yml")
        return Conseil(
            fichier, f"lefthook reecrit ses scripts : ajoute ce bloc a {chemins.relatif(fichier)}"
                     " (dans ta section `pre-push:` si tu en as deja une)",
            f"pre-push:\n  commands:\n    lintorn:\n      run: {en_yaml}\n      use_stdin: true",
            "yaml", "lefthook install")
    if outil == "simple-git-hooks":
        fichier = sommet / "package.json"
        commande = json.dumps(f'{script} "$@"', ensure_ascii=False)
        return Conseil(
            fichier, f"simple-git-hooks reecrit ses scripts : ajoute cette entree a "
                     f"{chemins.relatif(fichier)}, dans l'objet `simple-git-hooks`",
            f'"pre-push": {commande}', "json", "npx simple-git-hooks")
    # husky 9 fait lire à git `.husky/_/`, des relais régénérés à chaque
    # `npm install` qui lancent `.husky/<hook>`. Une ligne ajoutée au relais
    # n'y tourne jamais : il rend la main avant elle.
    dossier = autres.dossier
    if dossier.name == "_" and dossier.parent.name == ".husky":
        dossier = dossier.parent
    fichier = dossier / "pre-push"
    portee = _partage_par_tous(autres.reglage)
    garde = (f"ATTENTION : ce dossier sert a TOUS tes projets (reglage `git config --{portee}`).\n"
             "Cette ligne y tournerait aussi dans ceux qui n'ont pas Lintorn, et bloquerait\n"
             "chacun de leurs push : ne l'ajoute que si tous tes projets ont Lintorn."
             if portee else "")
    return Conseil(fichier, f"ajoute cette ligne a {chemins.relatif(fichier)}, avant tout `exit`"
                            " (cree-le s'il n'existe pas, et rends-le executable)",
                   ligne_a_ajouter(), "bash", garde=garde)


def _partage_par_tous(reglage: str) -> str:
    """"global" ou "system" si ce `core.hooksPath` vaut pour tous les projets ; "" sinon.

    Le conseil y faisait ajouter la ligne sans le dire : elle tournait alors
    dans chaque projet de la machine, et ceux sans Lintorn refusaient tous
    leurs push sur « not found ».
    """
    if not reglage:
        return ""
    try:
        sortie = config.git("config", "--show-scope", "--get-all", "core.hooksPath").stdout
    except (OSError, subprocess.SubprocessError):
        return ""
    for ligne in sortie.splitlines():
        portee, _, valeur = ligne.partition("\t")
        if portee in ("global", "system") and valeur.replace("\\", "/") == reglage:
            return portee
    return ""


def decrire(autres: AutresHooks) -> str:
    """Les hooks en quelques mots : husky pose un relais pour chacun des 14 noms."""
    if autres.noms is None:
        return "dossier illisible"
    parlants = ("pre-commit", "pre-push", "commit-msg")
    noms = sorted(autres.noms, key=lambda nom: (nom not in parlants, nom))
    if len(noms) <= 4:
        return ", ".join(noms)
    return f"{', '.join(noms[:3])} + {len(noms) - 3} autres"


def _hooks_actifs(dossier: Path) -> list[str] | None:
    """Les hooks que git lancerait depuis `dossier` ; None s'il est illisible.

    ⚠️ Illisible n'est pas vide : compté comme vide, le dossier laissait
    `lintorn hook` brancher le sien par-dessus des hooks qu'il n'avait pas vus.
    """
    try:
        fichiers = list(dossier.iterdir())
    except (FileNotFoundError, NotADirectoryError):
        return []
    except OSError:
        return None
    # Exécutable sauf sous Windows : NTFS n'a pas de bit, Git Bash lance tout.
    return sorted(f.name for f in fichiers
                  if f.name in NOMS_DE_HOOKS and f.is_file()
                  and (os.name == "nt" or os.access(f, os.X_OK)))


def _dossier_designe(reglage: str) -> Path:
    """Le dossier qu'un `core.hooksPath` désigne : git le résout depuis le sommet."""
    chemin = Path(reglage)
    return chemin if chemin.is_absolute() else (config.SOMMET_GIT or config.RACINE) / reglage


def autres_hooks() -> AutresHooks | None:
    """Les hooks qui tournent aujourd'hui SANS Lintorn, et qu'il ferait taire.

    ⚠️ git ne lit qu'UN dossier de hooks. Poser `core.hooksPath` vers
    `.lintorn/hooks` ne s'ajoute pas aux hooks existants, il les REMPLACE :
    ceux de pre-commit, de husky ou écrits à la main cessaient de tourner, sans
    un mot. Rend None quand il n'y a rien à protéger, ou que c'est déjà nous.
    """
    try:
        actuel = config.git("config", "--get", "core.hooksPath").stdout.strip().replace("\\", "/")
        if actuel and _meme_dossier(actuel, config.HOOKS_POUR_GIT):
            return None
        if actuel:
            dossier = _dossier_designe(actuel)
        else:
            relatif = config.git("rev-parse", "--git-path", "hooks").stdout.strip()
            if not relatif:
                return None
            dossier = config.RACINE / relatif
    except (OSError, subprocess.SubprocessError):
        return None
    noms = _hooks_actifs(dossier)
    return AutresHooks(dossier, noms, actuel) if noms != [] else None


def lintorn_voisin(autres: AutresHooks) -> Path | None:
    """Le sous-projet du même dépôt dont le hook Lintorn tient la place, s'il en est un.

    Dans un monorepo à plusieurs Lintorn, git ne lance que le hook branché :
    c'est lui qui lance celui des autres sous-projets. Rien à ajouter nulle part.
    """
    dossier = autres.dossier
    if (dossier.name != "hooks" or dossier.parent.name != ".lintorn"
            or "pre-push" not in (autres.noms or ()) or config.SOMMET_GIT is None):
        return None
    projet = dossier.parent.parent
    try:
        dans_le_depot = projet.resolve().is_relative_to(config.SOMMET_GIT.resolve())
        ailleurs = projet.resolve() != config.RACINE.resolve()
    except OSError:
        return None
    return projet if dans_le_depot and ailleurs else None


def lance_ses_voisins(projet: Path) -> bool:
    """La copie du hook de `projet` lance-t-elle les autres sous-projets ?"""
    try:
        texte = (projet / ".lintorn" / "hooks" / "pre-push").read_text(encoding="utf-8",
                                                                        errors="replace")
    except OSError:
        return False
    return MARQUE_VOISINS in texte


def visible_des_voisins() -> bool:
    """Le hook d'un autre sous-projet trouve-t-il celui-ci ? Il cherche les `.lintorn/` que git voit.

    Un `.lintorn/` ignoré par git (un `.gitignore` du dépôt l'écarte) n'est pas trouvé.
    """
    try:
        sortie = config.git("ls-files", "-co", "--exclude-standard", "--",
                            *(f"{config.DOSSIER_LINTORN.name}/{nom}"
                              for nom in ("config.toml", "regles.toml", ".gitignore")),
                            cwd=config.RACINE)
    except (OSError, subprocess.SubprocessError):
        return False
    return sortie.returncode == 0 and bool(sortie.stdout.strip())


def dans_le_depot(projet: Path) -> str:
    """Un sous-projet nommé depuis le sommet du dépôt : `api`."""
    try:
        return projet.resolve().relative_to(config.SOMMET_GIT.resolve()).as_posix()
    except (ValueError, OSError, AttributeError):
        return chemins.relatif(projet)


def mettre_a_jour_chez(projet: Path) -> str:
    """La commande qui repose le hook d'un autre sous-projet, depuis le sommet du dépôt."""
    return f"LINTORN_RACINE={shlex.quote(dans_le_depot(projet))} lintorn hook"


def hooks_rendus_muets() -> list[AutresHooks]:
    """Lintorn tient `core.hooksPath` : les hooks qui, à cause de lui, ne tournent plus.

    Ceux du dossier par défaut — branché sans regarder, ou avec `--force`, le
    hook de Lintorn les remplace — et le dossier qu'un `--force` a remplacé,
    noté à ce moment-là : après coup, plus rien ne le désigne.
    """
    dossiers: list[tuple[Path, str]] = []
    try:
        commun = config.git("rev-parse", "--git-common-dir").stdout.strip()
    except (OSError, subprocess.SubprocessError):
        commun = ""
    if commun:
        dossiers.append((config.RACINE / commun / "hooks", ""))
    remplace = base.lire_etat().get(CLE_REMPLACES)
    if isinstance(remplace, str) and remplace:
        dossiers.append((_dossier_designe(remplace), remplace))

    muets, vus = [], set()
    for dossier, reglage in dossiers:
        try:
            cle = dossier.resolve()
        except OSError:
            cle = dossier
        if cle in vus or _meme_dossier(str(dossier), config.HOOKS_POUR_GIT):
            continue
        vus.add(cle)
        noms = _hooks_actifs(dossier)
        if noms != []:
            muets.append(AutresHooks(dossier, noms, reglage))
    return muets


def pour_les_remettre(muets: list[AutresHooks]) -> tuple[str, Conseil]:
    """La commande qui rend la place à ces hooks, et quoi ajouter ensuite pour garder Lintorn."""
    # Le dossier qu'un `--force` a remplacé est celui que git lisait avant.
    remis = next((m for m in muets if m.reglage), muets[0])
    retour = (f"git config core.hooksPath {shlex.quote(remis.reglage)}" if remis.reglage
              else "git config --unset core.hooksPath")
    return retour, conseil(remis)


def _commits_pousses(avec_head: bool) -> list[str]:
    """Les commits que le hook dit pousser (`LINTORN_POUSSE`), et `HEAD` s'il le faut.

    `HEAD` est le seul repère quand un outil ne transmet pas la liste (pre-commit).
    """
    commits = os.environ.get("LINTORN_POUSSE", "").split()
    if avec_head or not commits:
        try:
            commits.append(config.git("rev-parse", "-q", "--verify", "HEAD").stdout.strip())
        except (OSError, subprocess.SubprocessError):
            pass
    return [c for c in dict.fromkeys(commits) if _UN_COMMIT.fullmatch(c) and c.strip("0")]


def _trace_ici() -> dict:
    trace = base.lire_etat().get(CLE_PASSAGE)
    return trace if isinstance(trace, dict) else {}


def noter_passage() -> None:
    """Lintorn lancé par un hook note quand, et quels commits : la PREUVE que ce hook l'appelle.

    ⚠️ Les commits s'AJOUTENT à ceux d'avant. Remplacés, une tentative refusée
    dans la même seconde que le push précédent effaçait le commit vérifié : le
    contrôle disait ce push parti sans Lintorn.
    """
    trace = _trace_ici()
    anciens = [c for c in trace.get("commits", []) if isinstance(c, str)] \
        if isinstance(trace.get("commits"), list) else []
    trace["quand"] = datetime.now().astimezone().isoformat(timespec="seconds")
    trace["commits"] = list(dict.fromkeys(_commits_pousses(avec_head=True) + anciens))[:TRACE_MAX]
    base.ecrire_etat(CLE_PASSAGE, trace)


def noter_verdict(code: int) -> None:
    """Après l'audit : un refus SANS terminal est noté, avec son heure.

    Sans terminal, personne ne peut répondre « o » : le refus est définitif.
    Si le push part quand même, c'est que le hook qui appelle Lintorn n'a pas
    transmis son code (`|| exit 1` oublié), ou un `--no-verify`. Lintorn
    affichait « PUSH ANNULE », le push partait, et rien ne le disait ensuite.

    Avec un terminal, c'est l'utilisateur qui tranche : son refus n'est pas
    noté, et il EFFACE celui d'avant. Un push refusé depuis un éditeur, puis
    forcé par « o » dans un terminal, faisait accuser le hook de ne pas
    transmettre le refus.
    """
    if code not in (0, 1, 3):
        return
    sans_recours = code == 1 and os.environ.get("LINTORN_TERMINAL") == "0"
    trace = _trace_ici()
    refuses = trace.get("refuses") if isinstance(trace.get("refuses"), dict) else {}
    for commit in _commits_pousses(avec_head=False):
        refuses.pop(commit, None)
        if sans_recours:
            refuses[commit] = int(datetime.now().timestamp())
    trace["refuses"] = dict(list(refuses.items())[-TRACE_MAX:])
    base.ecrire_etat(CLE_PASSAGE, trace)


def projets_jumeaux() -> list[Path]:
    """Ce même projet, dans les AUTRES worktrees du dépôt (ceux de Claude Code compris).

    ⚠️ `core.hooksPath` est commun à tous les worktrees, mais un chemin
    relatif se résout dans chacun. Sans sa propre copie du hook — ignorée par
    git, donc absente d'un worktree neuf —, un worktree pousse sans rien
    lancer, et sans un mot.
    """
    if config.SOMMET_GIT is None:
        return []
    try:
        dedans = config.RACINE.resolve().relative_to(config.SOMMET_GIT.resolve())
        sortie = config.git("worktree", "list", "--porcelain")
    except (OSError, ValueError, subprocess.SubprocessError):
        return []
    ici = config.SOMMET_GIT.resolve()
    jumeaux = []
    for bloc in sortie.stdout.split("\n\n"):
        lignes = bloc.splitlines()
        if not lignes or not lignes[0].startswith("worktree ") or "bare" in lignes:
            continue
        arbre = Path(lignes[0][len("worktree "):])
        try:
            if arbre.resolve() == ici or not (arbre / dedans).is_dir():
                continue
        except OSError:
            continue
        jumeaux.append(arbre / dedans)
    return jumeaux


class _Trace(NamedTuple):
    vu: datetime | None
    commits: set[str]             # vus par Lintorn pendant un push
    refuses: dict[str, int]       # refusés sans recours : commit -> heure (secondes epoch)


def _trace(projet: Path) -> _Trace:
    """Le passage noté dans `projet` — rien, si son `etat.json` est commité.

    Commité, ce n'est pas l'état de CETTE machine : un dépôt piégé y mettrait
    un passage daté de demain, et le contrôle le croirait.
    """
    rien = _Trace(None, set(), {})
    etat = projet / config.ETAT.relative_to(config.RACINE)
    # `is_file()` : un tube nommé à cette place se lirait sans fin.
    if not etat.is_file():
        return rien
    try:
        if config.git("ls-files", "--error-unmatch", "--", etat.relative_to(projet).as_posix(),
                      cwd=projet).returncode == 0:
            return rien
        trace = json.loads(etat.read_text(encoding="utf-8")).get(CLE_PASSAGE)
        vu = datetime.fromisoformat(trace["quand"])
    except (OSError, ValueError, AttributeError, KeyError, TypeError,
            subprocess.SubprocessError):
        return rien
    if vu.timestamp() > datetime.now().timestamp() + 3600:
        return rien      # daté du futur : ne prouve rien
    commits = trace.get("commits")
    refuses = trace.get("refuses")
    return _Trace(
        vu, {c for c in commits if isinstance(c, str)} if isinstance(commits, list) else set(),
        {c: h for c, h in refuses.items() if isinstance(h, int)}
        if isinstance(refuses, dict) else {})


def _dernier_passage() -> _Trace:
    """Le passage le plus récent, ici ou dans un autre worktree, et tous les commits notés.

    Le push se voit depuis tous les worktrees (le journal des branches distantes
    est commun), le passage seulement dans celui qui a poussé : lu ici seul,
    un push fait — et vérifié — depuis un autre worktree passait pour parti sans Lintorn.
    """
    vus, commits, refuses = [], set(), {}
    for projet in (config.RACINE, *projets_jumeaux()):
        trace = _trace(projet)
        if trace.vu is not None:
            vus.append(trace.vu)
            commits |= trace.commits
            for commit, heure in trace.refuses.items():
                refuses[commit] = max(heure, refuses.get(commit, heure))
    return _Trace(max(vus, key=lambda moment: moment.timestamp()) if vus else None,
                  commits, refuses)


def _push_notes() -> list[tuple[int, str]]:
    """Les push que git a notés : (heure en secondes epoch, commit envoyé)."""
    try:
        sortie = config.git("reflog", "show", "--date=unix", "--format=%H%x09%gd%x09%gs",
                            "--remotes")
    except (OSError, subprocess.SubprocessError):
        return []
    notes = []
    for ligne in sortie.stdout.splitlines():
        commit, _, reste = ligne.partition("\t")
        reference, _, libelle = reste.partition("\t")
        if libelle != LIBELLE_PUSH or "@{" not in reference:
            continue
        try:
            notes.append((int(reference[reference.rindex("@{") + 2:].rstrip("}")), commit))
        except ValueError:
            continue
    return notes


def passage(depuis: float | None = None) -> Passage:
    """Le hook appelle-t-il Lintorn ? Seul ce qui s'est PASSÉ en décide.

    `depuis` (secondes epoch) : ne regarder que les push faits depuis ce moment.

    ⚠️ Lire le pre-push d'un autre outil pour y chercher le mot « lintorn »
    rendait un vert sur un commentaire, un `echo`, une ligne commentée, un
    script non exécutable, ou le relais de husky qui rend la main avant la
    ligne : Lintorn ne tournait pas, et le contrôle disait qu'il tournait.

    Couvert quand Lintorn a vérifié le commit du dernier push — il tourne
    AVANT que git n'envoie, donc avant que le push ne soit noté — ou quand il
    a tourné après lui (une tentative refusée : le hook est branché).
    ⚠️ Comparer les seules HEURES laissait une tentative refusée couvrir le
    push suivant d'un autre commit, parti alors que la ligne avait disparu
    (`lefthook install` réécrit le script). Un `--no-verify` du commit refusé
    reste couvert : le hook est branché, c'est ce push-là qui l'a contourné.
    `malgre_refus` le dit quand même, quand le refus était sans recours.
    """
    vu, commits, refuses = _dernier_passage()
    notes = [(heure, commit) for heure, commit in _push_notes()
             if depuis is None or heure >= depuis]
    if not notes:
        return Passage(vu, None, vu is not None)
    dernier = max(heure for heure, _ in notes)
    # Un même `git push` met à jour toutes ses branches dans la même seconde. Une
    # marge de deux secondes fondait deux push distincts en un seul.
    envoyes = {commit for heure, commit in notes if heure == dernier}
    # `>=` : git note ses push à la seconde. Lintorn qui tourne dans la seconde
    # du push précédent (un push juste après un autre) le disait parti sans lui.
    couvert = vu is not None and (vu.timestamp() >= dernier or bool(commits & envoyes))
    malgre_refus = any(refuses.get(commit, dernier + 1) <= dernier for commit in envoyes)
    return Passage(vu, datetime.fromtimestamp(dernier).astimezone(), couvert, malgre_refus)


def _date(moment: datetime) -> str:
    return moment.astimezone().strftime("%d/%m/%Y a %H:%M")


def controle_hook_git() -> Resultat:
    """Le hook pre-push est-il RÉELLEMENT branché sur ce clone ?

    LA FAILLE : `core.hooksPath` vit dans `.git/config`, un fichier que git ne
    versionne PAS — et la copie du hook, dans `.lintorn/hooks/`, est écartée
    par le `.gitignore` de Lintorn. Sur un clone frais (autre PC, Codespaces,
    collègue), git regarde dans `.git/hooks/`, n'y trouve rien, ne dit rien,
    et le push part sans le moindre contrôle.

    C'est exactement le scénario que Lintorn traite partout ailleurs comme le plus
    grave : un garde-fou qui ne garde plus rien tout en paraissant sain.

    NON BLOQUANT exprès : quand le réglage manque, le hook ne tourne pas —
    bloquer un push serait donc de toute façon impossible. Ce contrôle sert aux
    lancements À LA MAIN, le seul moment où l'on peut encore s'en apercevoir.
    """
    titre = "Hook pre-push (Lintorn)"

    # Hors dépôt, ce contrôle n'a pas d'objet : il n'y a pas de push. Il
    # affichait pourtant « NON BRANCHE - `git push` ne controle RIEN », un
    # ROUGE impossible à corriger — et la commande qu'il proposait échouait.
    # Un rouge qu'on ne peut pas éteindre apprend à ignorer les rouges.
    if config.SOUS_GIT is None:
        return Resultat(titre, "INDISPONIBLE",
                        "git introuvable sur cette machine", bloquant=False)

    if not config.SOUS_GIT:
        return Resultat(
            titre, "INDISPONIBLE",
            "pas de depot git ici - aucun push a controler",
            "Ce dossier n'est pas versionne. **Trois controles sont donc sans "
            "objet**, et leur silence ne veut pas dire que tout va bien :\n\n"
            "- le **hook pre-push** : il n'y a pas de `git push` a intercepter ;\n"
            "- la **fraicheur des memoires** : elle se mesure en commits ;\n"
            "- le **perimetre `.gitignore`** : rien n'est exclu de l'audit.\n\n"
            "Les autres controles, eux, tournent normalement.",
            bloquant=False, detail_markdown=True,
        )

    try:
        # `git config --get` sort en 1 quand la clé est absente — précisément
        # le cas qu'on cherche. `config.git` ne lève jamais sur un code.
        sortie = config.git("config", "--get", "core.hooksPath")
    except (OSError, subprocess.SubprocessError) as erreur:
        return Resultat(titre, "ERREUR", f"git injoignable : {erreur}", bloquant=False)

    actuel = sortie.stdout.strip().replace("\\", "/")
    branche = _meme_dossier(actuel, config.HOOKS_POUR_GIT)
    # ⚠️ L'ABSENCE DU FICHIER SE JUGE APRÈS le réglage git, jamais avant.
    # Testée en premier, elle rendait « hook pas encore installe » — un gris
    # rassurant, réservé au premier lancement — pour un hook INSTALLÉ PUIS
    # DISPARU. Or il est ignoré par git (`.lintorn/.gitignore`), donc un
    # `git clean -fdX` l'efface : le garde-fou meurt, git ne dit rien, et le
    # push part sans audit derrière un message qui dit « pas encore ».
    present = (config.HOOKS / "pre-push").is_file()

    # Un autre outil tient déjà les hooks : conseiller `core.hooksPath` ferait
    # taire les siens. Lintorn tourne alors depuis LEUR pre-push.
    autres = None if branche else autres_hooks()
    if autres:
        return _controle_depuis_un_autre_hook(titre, autres)

    if branche and present:
        return _controle_parti_sans(titre, _controle_rien_de_muet(
            titre, _controle_hook_executable(titre), relatif=not Path(actuel).is_absolute()))

    if branche:
        return Resultat(
            titre, "ALERTE",
            "BRANCHE MAIS ABSENT - `git push` ne controle RIEN",
            "`core.hooksPath` pointe bien sur `" + config.HOOKS_POUR_GIT + "`, mais le "
            "fichier `pre-push` n'y est plus (ou n'est pas lisible). git cherche "
            "un hook, n'en trouve aucun, et laisse passer le push **sans un "
            "message**.\n\n"
            "Le hook est un fichier local, ignore par git : `git clean -fdX` "
            "(nettoyage des fichiers ignores) l'efface. Pour le reposer :\n\n"
            "```bash\nlintorn hook\n```",
            bloquant=False, detail_markdown=True,
        )

    if not present:
        # ⚠️ « a disparu » etait le PREMIER message vu par un nouvel
        # utilisateur, et il etait faux : le hook n'avait jamais ete installe.
        # Un outil qui accuse au premier lancement perd la confiance qu'il
        # lui faut pour etre cru la fois d'apres.
        return Resultat(
            titre, "INDISPONIBLE",
            "hook pas encore installe - `lintorn hook`",
            "Sans le hook, `git push` ne lance aucun controle — et sans le "
            "moindre message. Une seule commande, une fois par clone :\n\n"
            "```bash\nlintorn hook\n```",
            bloquant=False,
            detail_markdown=True,
        )

    etat = "non configure" if not actuel else f"pointe ailleurs ({actuel})"
    return Resultat(
        titre, "ALERTE",
        f"NON BRANCHE ({etat}) - `git push` ne controle RIEN",
        "`core.hooksPath` vit dans `.git/config`, un fichier que git **ne "
        "versionne pas** : il ne suit donc pas les clones. Tant qu'il n'est "
        "pas posé, `git push` n'exécute aucun contrôle — sans le moindre "
        "message d'avertissement.\n\n"
        "Pour le brancher (une seule fois par clone, depuis la racine) :\n\n"
        "```bash\n"
        f"git config core.hooksPath {config.HOOKS_POUR_GIT}\n"
        "```\n\n"
        "ou, strictement équivalent : `lintorn hook`",
        bloquant=False,
        detail_markdown=True,
    )


def _meme_dossier(configure: str, attendu: str) -> bool:
    """Deux ecritures du meme dossier de hooks designent-elles le meme endroit ?

    ⚠️ Comparer les CHAINES rendait un rouge permanent — « NON BRANCHE, git
    push ne controle RIEN » — a qui avait pose un chemin absolu, pourtant
    valide et parfaitement fonctionnel. Un rouge qu'aucune commande n'eteint
    apprend a ignorer les rouges.
    """
    if not configure:
        return False
    if configure == attendu:
        return True
    # git resout un chemin relatif depuis le sommet du depot.
    depuis = config.SOMMET_GIT or config.RACINE
    try:
        return (depuis / configure).resolve() == (depuis / attendu).resolve()
    except OSError:
        return False


def _comment_brancher(quoi: Conseil) -> str:
    ensuite = f"Puis lance `{quoi.ensuite}`.\n\n" if quoi.ensuite else ""
    garde = f"**{quoi.garde}**\n\n" if quoi.garde else ""
    return (
        f"Pour garder les deux, {quoi.consigne} :\n\n"
        f"```{quoi.langage}\n{quoi.ajout}\n```\n\n{ensuite}{garde}"
        f"Ça lance le hook de Lintorn, que `lintorn hook` pose dans `{config.HOOKS_ATTENDU}/` "
        "sans toucher aux tiens. Pousse ensuite une fois : ce contrôle ne passe au vert "
        "qu'après avoir **vu** Lintorn tourner pendant un push."
    )


def _bloc_sans_verbose(fichier: Path) -> bool:
    """Le bloc qui lance Lintorn, dans la config de pre-commit, n'a-t-il pas `verbose: true` ?"""
    try:
        lignes = fichier.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return False
    for numero, ligne in enumerate(lignes):
        if "entry:" not in ligne or ".lintorn/hooks/pre-push" not in ligne:
            continue
        # Le bloc : de son tiret d'élément de liste jusqu'au suivant.
        debut = next((i for i in range(numero, -1, -1) if lignes[i].lstrip().startswith("- ")), 0)
        retrait = len(lignes[debut]) - len(lignes[debut].lstrip())
        fin = next((i for i in range(numero + 1, len(lignes)) if lignes[i].strip()
                    and len(lignes[i]) - len(lignes[i].lstrip()) <= retrait), len(lignes))
        return not any(re.match(r"\s*verbose:\s*true\b", texte) for texte in lignes[debut:fin])
    return False


def _controle_lance_par_un_voisin(titre: str, voisin: Path, preuve: Passage) -> Resultat:
    """Le hook Lintorn d'un autre sous-projet est branché : il lance celui-ci, ou pas."""
    nom = f"{dans_le_depot(voisin)}/"
    if not lance_ses_voisins(voisin):
        return Resultat(
            titre, "ALERTE",
            f"le hook Lintorn de {nom} ne lance pas celui-ci - sa copie est d'une version precedente",
            f"git ne lance que le hook de `{nom}`, qui doit lancer aussi celui des autres "
            "sous-projets Lintorn du dépôt. Sa copie, d'une version précédente, ne le fait pas : "
            "ce sous-projet pousse **sans contrôle**. Pour la mettre à jour, depuis le sommet du "
            f"dépôt :\n\n```bash\n{mettre_a_jour_chez(voisin)}\n```",
            bloquant=False, detail_markdown=True,
        )
    if not visible_des_voisins():
        return Resultat(
            titre, "ALERTE",
            f"le hook Lintorn de {nom} ne trouve pas ce sous-projet - son .lintorn/ est ignore par git",
            f"Le hook de `{nom}` cherche les autres sous-projets Lintorn par leur `.lintorn/`, tel "
            "que git le voit. Celui-ci est écarté par un `.gitignore` du dépôt : ce sous-projet "
            "pousse **sans contrôle**. Ne laisse ignorer que ce que `lintorn init` écarte déjà "
            "(le `.gitignore` de `.lintorn/` garde la configuration).",
            bloquant=False, detail_markdown=True,
        )
    if preuve.malgre_refus:
        return Resultat(titre, "ALERTE",
                        f"ton dernier push ({_date(preuve.pousse)}) est parti alors que Lintorn "
                        "l'avait REFUSE",
                        "Lintorn a refusé ce push, sans terminal pour te demander ton avis, et il "
                        "est parti quand même : un `git push --no-verify`, le plus souvent.",
                        bloquant=False)
    if preuve.couvert:
        return Resultat(titre, "OK",
                        f"lance par le hook Lintorn de {nom} - vu tourner le {_date(preuve.vu)}",
                        bloquant=False)
    if preuve.vu is None:
        return Resultat(titre, "VERIF",
                        f"lance par le hook Lintorn de {nom} - pas encore vu tourner : pousse une fois",
                        bloquant=False)
    return Resultat(
        titre, "ALERTE",
        f"ton dernier push ({_date(preuve.pousse)}) est parti SANS Lintorn"
        f" - vu pour la derniere fois le {_date(preuve.vu)}",
        f"Le hook de `{nom}` lance celui-ci à chaque push, mais il n'a pas vérifié ce qui est "
        "parti au dernier : un `git push --no-verify`, ou un push qui n'a pas passé le contrôle "
        f"de `{nom}` (un refus arrête le push avant ce sous-projet).",
        bloquant=False, detail_markdown=True,
    )


def _controle_depuis_un_autre_hook(titre: str, autres: AutresHooks) -> Resultat:
    """Un autre outil tient les hooks : Lintorn tourne depuis LEUR pre-push, ou pas du tout."""
    preuve = passage()
    voisin = lintorn_voisin(autres)
    if voisin is not None:
        return _controle_lance_par_un_voisin(titre, voisin, preuve)
    if preuve.malgre_refus:
        return Resultat(
            titre, "ALERTE",
            f"ton dernier push ({_date(preuve.pousse)}) est parti alors que Lintorn l'avait REFUSE",
            "Lintorn a refusé ce push, sans terminal pour te demander ton avis, et il est parti "
            "quand même. Si ce n'est pas un `git push --no-verify` de ta part, ton hook appelle "
            "Lintorn **sans transmettre son refus** : la ligne qui l'appelle doit finir par "
            "`|| exit 1`, sinon ton script continue et le push part.\n\n"
            + _comment_brancher(conseil(autres)),
            bloquant=False, detail_markdown=True,
        )
    if preuve.couvert:
        # La ligne appelle une COPIE du hook, qu'une mise à jour de Lintorn ne touche pas.
        try:
            a_jour = _controle_hook_a_jour(titre, (config.HOOKS / "pre-push").read_bytes())
        except OSError:
            a_jour = None
        if a_jour and a_jour.statut != "OK":
            return a_jour
        quoi = conseil(autres)
        if _outil(autres) == "pre-commit" and _bloc_sans_verbose(quoi.fichier):
            return Resultat(
                titre, "VERIF",
                "pre-commit cache ce que dit Lintorn quand il laisse passer"
                " - `verbose: true` dans son bloc",
                "Sans `verbose: true`, pre-commit n'affiche ce que dit Lintorn que s'il refuse : "
                "« Push autorise SANS verification complete » devient « Passed ». Le bloc "
                "entier, à jour :\n\n" + _comment_brancher(quoi),
                bloquant=False, detail_markdown=True,
            )
        # « vu au dernier push » serait faux après un `--no-verify` qui suit
        # une tentative bloquée : le hook est branché, mais ce push l'a contourné.
        return Resultat(titre, "OK", f"appele par ton hook - vu tourner le {_date(preuve.vu)}",
                        bloquant=False)

    quoi = conseil(autres)
    if preuve.vu is None:
        return Resultat(
            titre, "ALERTE",
            f"pas branche : tes hooks ({decrire(autres)}) occupent la place"
            f" - `lintorn hook` dit quoi ajouter a {chemins.relatif(quoi.fichier)}",
            "git ne lit qu'**un seul** dossier de hooks, et celui-ci a déjà les tiens, dans "
            f"`{chemins.relatif(autres.dossier)}/`. Y brancher celui de Lintorn les rendrait "
            "**muets**, sans le moindre message. Et Lintorn n'a encore jamais été vu "
            "tourner pendant un push.\n\n" + _comment_brancher(quoi),
            bloquant=False, detail_markdown=True,
        )
    return Resultat(
        titre, "ALERTE",
        f"ton dernier push ({_date(preuve.pousse)}) est parti SANS Lintorn"
        f" - vu pour la derniere fois le {_date(preuve.vu)}",
        "Lintorn a déjà tourné depuis ton hook, mais il n'a pas vérifié ce qui est parti au "
        "dernier push. L'appel a pu être retiré, ou effacé par ton outil de hooks quand il a "
        "réécrit ses scripts ; le script n'est peut-être plus exécutable (git l'ignore alors "
        "sans un mot) ; ou ce push est parti avec `git push --no-verify`.\n\n"
        + _comment_brancher(quoi),
        bloquant=False, detail_markdown=True,
    )


def _controle_parti_sans(titre: str, resultat: Resultat) -> Resultat:
    """Le hook de Lintorn est branché : le dernier push l'a-t-il VRAIMENT lancé ?

    ⚠️ Branché et exécutable ne suffit pas : quand la commande `lintorn` est
    introuvable là d'où l'on pousse (un venv non activé, le bouton d'un
    éditeur), le hook laisse passer. Le contrôle affirmait ensuite « Lintorn
    tournera avant chaque push ». Seuls les push d'après la pose du hook comptent.
    """
    if resultat.statut == "ALERTE":
        return resultat
    if resultat.statut == "OK" and _journal_coupe():
        return Resultat(
            titre, "VERIF",
            "git ne note plus ses push (core.logAllRefUpdates = false)"
            " - impossible de prouver qu'ils passent par Lintorn",
            "Lintorn prouve qu'il a vérifié chaque push par le journal où git les note. Ce "
            "dépôt a coupé ce journal : un push parti sans Lintorn (un éditeur qui ne le "
            "trouve pas, un `--no-verify`) ne se verrait pas. Pour le rouvrir :\n\n"
            "```bash\ngit config --unset core.logAllRefUpdates\n```",
            bloquant=False, detail_markdown=True)
    try:
        # À la seconde, comme git note ses push : un push fait dans la seconde
        # de la pose compte.
        pose = int((config.HOOKS / "pre-push").stat().st_mtime)
    except OSError:
        return resultat
    preuve = passage(depuis=pose)
    if preuve.pousse is None or preuve.couvert:
        return resultat
    jamais = preuve.vu is None or preuve.vu.timestamp() < pose
    # Une copie d'une version précédente, jamais vue : elle peut venir d'avant
    # que Lintorn ne note ses passages. Juste après une mise à jour, le contrôle
    # accusait d'être parti SANS Lintorn un push que l'ancienne version avait
    # vérifié. La copie périmée, elle, est certaine.
    if jamais and resultat.statut == "VERIF" and _copie_perimee():
        return resultat
    return Resultat(
        titre, "ALERTE",
        f"ton dernier push ({_date(preuve.pousse)}) est parti SANS Lintorn - "
        + ("jamais vu tourner pendant un push" if jamais
           else f"vu pour la derniere fois le {_date(preuve.vu)}"),
        "Le hook est branché, mais Lintorn n'a pas vérifié ce qui est parti au dernier push. "
        "Le plus souvent, la commande `lintorn` était introuvable là d'où tu as poussé : un venv "
        "non activé, ou le bouton d'un éditeur qui ne voit pas le même PATH que ton terminal. "
        "Le hook l'a dit (« Lintorn introuvable »), puis a laissé passer. Ou ce push est parti "
        "avec `git push --no-verify`.\n\n"
        "Pour que le hook trouve Lintorn de partout, installe-le pour tout ton compte :\n\n"
        "```bash\npipx install lintorn\n```\n\n"
        "Ce contrôle repasse au vert au premier push que Lintorn vérifie.",
        bloquant=False, detail_markdown=True,
    )


def _journal_coupe() -> bool:
    """git a-t-il cessé de noter les mises à jour de ses branches, push compris ?"""
    try:
        valeur = config.git("config", "--get", "core.logAllRefUpdates").stdout.strip().lower()
    except (OSError, subprocess.SubprocessError):
        return False
    return valeur in ("false", "no", "off", "0")


def _copie_perimee() -> bool:
    try:
        return ((config.HOOKS / "pre-push").read_bytes()
                != (config.HOOKS_SOURCE / "pre-push").read_bytes())
    except OSError:
        return False


def _controle_rien_de_muet(titre: str, resultat: Resultat, relatif: bool = True) -> Resultat:
    """Le hook de Lintorn est branché ici — d'autres hooks, ou d'autres worktrees, se taisent-ils ?"""
    if resultat.statut == "ALERTE":
        return resultat     # Lintorn lui-même ne tourne pas : c'est ça qu'il faut réparer d'abord
    muets = hooks_rendus_muets()
    if not muets:
        # Un `core.hooksPath` absolu désigne le même dossier depuis tous les worktrees.
        return _controle_des_worktrees(titre, resultat) if relatif else resultat
    liste = " ; ".join(f"{decrire(m)} ({chemins.relatif(m.dossier)}/)" for m in muets)
    retour, quoi = pour_les_remettre(muets)
    return Resultat(
        titre, "ALERTE",
        f"branche, mais ces hooks ne tournent plus : {liste}",
        "git ne lit qu'**un seul** dossier de hooks : tant que `core.hooksPath` désigne "
        "celui de Lintorn, ceux-ci ne sont plus lancés, sans le moindre message.\n\n"
        f"Pour les remettre en service :\n\n```bash\n{retour}\n```\n\n"
        + _comment_brancher(quoi)
        + "\n\nS'ils ne servent plus, retire-les (ou retire-leur le bit exécutable) : "
        "ce contrôle se taira.",
        bloquant=False, detail_markdown=True,
    )


def _vu_d_ici(projet: Path) -> str:
    """Un autre worktree, depuis celui-ci (`../agent`) : un chemin absolu porterait le nom
    de l'utilisateur dans le rapport."""
    try:
        return os.path.relpath(projet, config.RACINE).replace("\\", "/")
    except ValueError:      # sous Windows, sur un autre disque
        return str(projet)


def _controle_des_worktrees(titre: str, resultat: Resultat) -> Resultat:
    """Les autres worktrees ont-ils leur copie du hook ? Sans elle, leurs push ne lancent rien.

    ⚠️ Branché ici, le contrôle disait « Lintorn tournera avant chaque push »
    pendant qu'un worktree — ceux que Claude Code crée pour ses agents compris —
    poussait sans aucun contrôle.
    """
    sans = [projet for projet in projets_jumeaux()
            if not (projet / config.HOOKS_ATTENDU / "pre-push").is_file()]
    if not sans:
        return resultat
    noms = ", ".join(_vu_d_ici(projet) for projet in sans[:3])
    noms += f" + {len(sans) - 3} autres" if len(sans) > 3 else ""
    commandes = "\n".join(f'cd "{_vu_d_ici(projet)}" && lintorn hook' for projet in sans)
    return Resultat(
        titre, "ALERTE",
        f"branche ici, mais un push depuis ce(s) worktree(s) ne controle RIEN : {noms}",
        "`core.hooksPath` vaut pour tous les worktrees du dépôt, mais chacun cherche le hook "
        "dans **son** dossier `.lintorn/hooks/` — une copie ignorée par git, donc absente "
        "d'un worktree neuf. git n'y trouve rien, et le push part **sans un message**.\n\n"
        f"Pour y poser le hook :\n\n```bash\n{commandes}\n```\n\n"
        "Un worktree qui ne sert plus se retire avec `git worktree remove` : ce contrôle se taira.",
        bloquant=False, detail_markdown=True,
    )


def _controle_hook_executable(titre: str) -> Resultat:
    """`core.hooksPath` est bon — reste à savoir si git a le DROIT de lancer.

    LA PANNE : git refuse d'exécuter un hook qui n'a pas le bit exécutable,
    et il le fait EN SILENCE — pas de message, pas d'erreur, le
    push part simplement sans contrôle. Le hook avait été créé sous Windows, où
    ce bit n'existe pas (`core.filemode=false`, Git Bash lance tout) ; il est
    donc parti dans le dépôt en 100644. Tant que le projet est resté sous
    Windows, personne n'a rien vu. Au passage sous Linux, le hook est mort ce
    jour-là — et Lintorn affichait toujours `[ OK ] branche`.

    C'était donc le pire cas possible : pas un rouge, pas même un `[ERR!]`, mais
    un VERT sur un garde-fou mort. Plusieurs jours de push en confiance.

    DEUX vérifications, parce que ce sont deux pannes différentes :
      * le bit sur le DISQUE   -> décide si git lance le hook ICI, maintenant
      * le mode dans l'INDEX   -> décide s'il le lancera sur TOUS les clones
    Réparer l'un sans l'autre laisse la moitié du problème en place : un
    `chmod` seul se perd au prochain clone, un mode git seul ne débloque pas la
    machine courante tant que le fichier n'est pas ressorti du dépôt.
    """
    chemin = config.HOOKS / "pre-push"
    fautes: list[str] = []

    # 0. LE CONTENU. git doit LIRE le script pour l'exécuter, et l'interpréteur
    #    du shebang doit exister : `#!/bin/sh\r` (fins de ligne Windows) n'en
    #    est pas un. Les deux échouent sur un `fatal: cannot exec` que rien ne
    #    relie au hook, et le contrôle annonçait « branche et executable ».
    try:
        installe = chemin.read_bytes()
    except OSError:
        installe = None
        fautes.append("illisible (droits) : git ne peut pas lire le script")
    # N'IMPORTE OU dans le fichier, et pas seulement en fin de ligne : `sh`
    # lit le `\r` comme un caractere de la commande (`$'\r': commande
    # introuvable`). Ne regarder que le shebang laissait passer un fichier aux
    # fins de ligne melangees — annonce « PERIME » alors qu'il etait mort.
    if installe is not None and b"\r" in installe:
        fautes.append("retour chariot (CR) : `sh` ne sait pas lire ce script")

    # 1. LE DISQUE. Sauté sous Windows : NTFS n'a pas de bit exécutable, et
    #    `os.access(X_OK)` y répond n'importe quoi. Là-bas, Git Bash lance le
    #    hook quel que soit le mode — le seul vrai risque est le mode git.
    if os.name != "nt" and not os.access(chemin, os.X_OK):
        fautes.append("pas executable sur le disque")

    # 2. L'INDEX GIT. Le mode voyage avec le dépôt : c'est lui qui décide du
    #    sort de Codespaces et de toute machine future.
    mode = _mode_git(chemin)
    if mode is not None and not mode.endswith("755"):
        fautes.append(f"enregistre en {mode} dans git (attendu 100755)")

    if not fautes:
        return _controle_hook_a_jour(titre, installe)

    return Resultat(
        titre, "ALERTE",
        f"BRANCHE MAIS MUET - {' + '.join(fautes)}",
        "`core.hooksPath` est bien posé, mais **git n'exécutera pas** ce "
        "fichier : il refuse tout hook dépourvu du bit exécutable, et il le "
        "fait **sans le moindre message**. `git push` repart donc sans aucun "
        "contrôle, avec un voyant au vert.\n\n"
        "Les deux lignes de la réparation (les deux sont nécessaires) :\n\n"
        "```bash\n"
        f"chmod +x {config.HOOKS_ATTENDU}/pre-push\n"
        f"git add {config.HOOKS_ATTENDU}/pre-push\n"
        "```\n\n"
        "`chmod` débloque **cette machine**, `git add` enregistre le mode "
        "`100755` dans le dépôt pour **tous les clones à venir**. Sous Windows, "
        "où `chmod` n'a pas d'effet, la seconde ligne devient "
        f"`git update-index --chmod=+x {config.HOOKS_ATTENDU}/pre-push`.\n\n"
        "Si c'est le CONTENU qui est en cause (illisible, fins de ligne "
        "Windows), `lintorn hook` repose une copie saine.",
        bloquant=False,
        detail_markdown=True,
    )


def _controle_hook_a_jour(titre: str, installe: bytes) -> Resultat:
    """Branché, exécutable — mais est-ce le hook de CETTE version de Lintorn ?

    LA PANNE : le hook posé dans le projet est une COPIE, figée le jour de
    `lintorn hook`. `pip install -U lintorn` met à jour le paquet, jamais
    elle : un correctif du hook n'atteignait donc aucun projet déjà équipé.
    Vécu : l'ancien hook passait les fichiers poussés sans séparateur `--`.
    Un fichier SUPPRIMÉ nommé `--help` y redevenait l'option, l'aide
    s'affichait, et le push partait sans audit.

    VERIF et non ALERTE : un hook périmé contrôle encore presque tout. Mais
    le dire ici est le seul chemin par lequel le correctif arrive jusqu'au
    projet.
    """
    # ⚠️ Comparaison OCTET POUR OCTET. Neutraliser les CRLF « pour tolérer un
    # checkout Windows » rendait vert un hook que git ne peut pas exécuter ;
    # c'est `_controle_hook_executable` qui les refuse, juste avant.
    try:
        livre = (config.HOOKS_SOURCE / "pre-push").read_bytes()
    except OSError as erreur:
        return Resultat(titre, "VERIF",
                        f"hook livre illisible ({erreur.strerror}) - "
                        "impossible de dire si la copie est a jour",
                        bloquant=False)

    if installe == livre:
        return Resultat(titre, "OK", "branche et executable - Lintorn tournera avant chaque push")

    return Resultat(
        titre, "VERIF",
        "branche mais PERIME - `lintorn hook`",
        "Le hook posé dans ce projet n'est pas celui de la version de Lintorn "
        "installée. `pip install -U lintorn` met à jour le paquet, **jamais** "
        "la copie posée par `lintorn hook` : les correctifs du hook ne "
        "t'atteignent donc pas. Pour la remplacer :\n\n"
        "```bash\nlintorn hook\n```\n\n"
        "Un hook modifié à la main tombe aussi ici, et la commande écrasera "
        "tes modifications. Ce que tu veux lancer à chaque push a sa place "
        "dans `[[commandes]]` : le hook les exécute déjà, sauf celles marquées "
        "`lent`.",
        bloquant=False, detail_markdown=True,
    )


def _mode_git(chemin: Path) -> str | None:
    """Mode enregistré dans l'index git (`100644`, `100755`), ou None.

    None = question sans réponse fiable (git muet, fichier pas encore suivi) →
    l'appelant ne doit alors RIEN conclure. Un contrôle qui invente un verdict
    quand il n'a pas la donnée est exactement le défaut qu'on corrige ici.
    """
    try:
        # `relative_to` lève ValueError sur un chemin hors dépôt : c'est une
        # question sans réponse, pas une panne — donc None comme le reste.
        relatif = chemin.relative_to(config.RACINE).as_posix()
        sortie = config.git("ls-files", "-s", "--", relatif)
    except (OSError, ValueError, subprocess.SubprocessError):
        return None

    premiere = sortie.stdout.strip().split("\n")[0] if sortie.stdout.strip() else ""
    return premiere.split()[0] if premiere else None
